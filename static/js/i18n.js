    function translate(value) {
        if (value == null || language === 'zh') return value;
        const source = String(value);
        const trimmed = source.trim();
        if (english[trimmed]) return source.replace(trimmed, english[trimmed]);
        for (const [pattern, replacement] of formattedTranslations) {
            const match = trimmed.match(pattern);
            if (match) return source.replace(trimmed, typeof replacement === 'function' ? replacement(match) : trimmed.replace(pattern, replacement));
        }
        let result = source;
        for (const [from, to] of phraseTranslations) result = result.split(from).join(to);
        return result;
    }

